N = len(Q)

# t = 1, 2, ..., 114
t = np.arange(1, N + 1)

# Arrays
X = np.zeros(N, dtype=complex)
power = np.zeros(N)
frequency = np.zeros(N)

# MANUAL DFT
for k in range(N):

    real_part = 0
    imaginary_part = 0

    for j in range(N):

        angle = 2 * np.pi * k * t[j] / N

        real_part += Q[j] * np.cos(angle)
        imaginary_part -= Q[j] * np.sin(angle)

    X[k] = real_part + 1j * imaginary_part

    power[k] = X[k].real**2 + X[k].imag**2

    frequency[k] = k / N


# POWER vs FREQUENCY
half = N // 2

plt.figure(figsize=(9, 5))

plt.plot(frequency[1:half+1], power[1:half+1])

plt.xlabel("Frequency (cycles/year)")
plt.ylabel("Power")
plt.title("Power vs Frequency")

plt.grid(True)
